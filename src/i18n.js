export const SUPPORTED_LANGUAGE_ORDER = ['pt', 'en', 'zh', 'hi', 'es', 'fr', 'ar', 'bn', 'ru', 'ur'];

export function isRtlLanguage(language) {
  return language === 'ar' || language === 'ur';
}

export function getDeviceLanguage() {
  const locale = getLocales?.()?.[0];
  const tag = locale?.languageTag?.toLowerCase?.() ?? 'en';
  const code = locale?.languageCode?.toLowerCase?.() ?? tag.split('-')[0];
  if (translations[code]) return code;
  if (tag.startsWith('pt')) return 'pt';
  if (tag.startsWith('zh')) return 'zh';
  if (tag.startsWith('hi')) return 'hi';
  if (tag.startsWith('es')) return 'es';
  if (tag.startsWith('fr')) return 'fr';
  if (tag.startsWith('ar')) return 'ar';
  if (tag.startsWith('bn')) return 'bn';
  if (tag.startsWith('ru')) return 'ru';
  if (tag.startsWith('ur')) return 'ur';
  return 'en';
}

export function createTranslator(language) {
  const lang = translations[language] ? language : 'en';
  return (key) => {
    const parts = key.split('.');
    let current = translations[lang];
    for (const part of parts) current = current?.[part];
    if (typeof current === 'string') return current;
    let fallback = translations.en;
    for (const part of parts) fallback = fallback?.[part];
    return typeof fallback === 'string' ? fallback : key;
  };
}

export function getLocalizedContent(language) {
  const lang = translations[language] ? language : 'en';
  return translations[lang];
}
