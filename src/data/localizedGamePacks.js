function localizedPacks(language) {
  if (language === 'pt') return null;
  if (language === 'zh') return ZH_PACKS;
  return EN_PACKS;
}

export function getOptionLabel(language, value) {
  if (language === 'pt') {
    const ptLabels = {
      medio: 'médio',
      familia: 'família',
      caotico: 'caótico',
      profissoes: 'profissões',
    };
    return ptLabels[value] ?? value;
  }
  return OPTION_LABELS[language]?.[value] ?? OPTION_LABELS.en[value] ?? value;
}

export function getLocalizedPromptPack(language, packName, fallbackPack) {
  return localizedPacks(language)?.[packName] ?? fallbackPack;
}

export function getLocalizedPackList(language, packName, key, fallbackPack, fallbackKey) {
  const pack = getLocalizedPromptPack(language, packName, fallbackPack);
  return pack?.[key] ?? pack?.[fallbackKey] ?? fallbackPack?.[key] ?? fallbackPack?.[fallbackKey] ?? [];
}

export function getLocalizedImpostorWords(language, fallbackWords) {
  return localizedPacks(language)?.impostorWords ?? fallbackWords;
}
